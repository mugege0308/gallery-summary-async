[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$ImagesRoot = "",
    [int]$Port = 8765
)

$ErrorActionPreference = "Stop"
$ProjectRoot = Split-Path -Parent $MyInvocation.MyCommand.Path
$GalleryUrl = "http://127.0.0.1:$Port/"
$PidDirectory = Join-Path $ProjectRoot ".gallery"
$PidFile = Join-Path $PidDirectory "gallery_server.pid.json"
$AccessInfoFile = Join-Path $PidDirectory "access_urls.txt"
$ImagesRootFile = Join-Path $PidDirectory "images_root.txt"
$MutexName = "Local\CodexLocalImageGalleryLauncher"
$GallerySecretEnvironmentNames = @(
    "GALLERY_GENERATION_AUTH_TOKEN",
    "GALLERY_GENERATION_SESSION_SECRET"
)

function Import-GallerySecretEnvironment {
    foreach ($name in $GallerySecretEnvironmentNames) {
        $processValue = [Environment]::GetEnvironmentVariable($name, "Process")
        if (-not [string]::IsNullOrWhiteSpace($processValue)) {
            continue
        }

        $userValue = [Environment]::GetEnvironmentVariable($name, "User")
        if (-not [string]::IsNullOrWhiteSpace($userValue)) {
            # Start-Process inherits this launcher environment.  Never log or
            # pass the secret as a command-line argument.
            [Environment]::SetEnvironmentVariable($name, $userValue, "Process")
        }
    }
}

function Test-GalleryReady {
    try {
        $response = Invoke-WebRequest -UseBasicParsing -Uri "$GalleryUrl/api/config" -TimeoutSec 2
        return $response.StatusCode -eq 200
    } catch {
        return $false
    }
}

function Wait-GalleryReady {
    param([int]$TimeoutSeconds = 120)
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    do {
        if (Test-GalleryReady) { return $true }
        Start-Sleep -Seconds 1
    } while ((Get-Date) -lt $deadline)
    return $false
}

function Find-ComfyOutput {
    $desktop = Join-Path $env:USERPROFILE "Desktop"
    $matches = Get-ChildItem -LiteralPath $desktop -Directory -Recurse -Filter "ComfyUI" -ErrorAction SilentlyContinue |
        Where-Object {
            $_.FullName -like "*\StabilityMatrix-win-x64\Data\Packages\ComfyUI" -and
            (Test-Path -LiteralPath (Join-Path $_.FullName "output"))
        }
    $match = $matches | Select-Object -First 1
    if ($match) { return (Join-Path $match.FullName "output") }
    return $null
}

function Find-TailscaleIPv4 {
    $pattern = '\b100\.(?:6[4-9]|[7-9]\d|1[01]\d|12[0-7])\.\d{1,3}\.\d{1,3}\b'
    $addresses = New-Object System.Collections.Generic.List[string]
    $tailscaleCommand = Get-Command tailscale.exe -ErrorAction SilentlyContinue
    if ($tailscaleCommand) {
        # Tailscale's local API can be inaccessible to a non-admin shell even
        # while the adapter is up.  Detection is optional; never let that
        # failure prevent the localhost gallery from starting.
        try {
            $cliOutput = (& $tailscaleCommand.Source ip -4 2>$null | Out-String)
        } catch {
            $cliOutput = ""
        }
        foreach ($match in [regex]::Matches($cliOutput, $pattern)) {
            if (-not $addresses.Contains($match.Value)) { [void]$addresses.Add($match.Value) }
        }
    }
    $ipconfigOutput = (ipconfig /all | Out-String)
    foreach ($match in [regex]::Matches($ipconfigOutput, $pattern)) {
        if (-not $addresses.Contains($match.Value)) { [void]$addresses.Add($match.Value) }
    }
    return @($addresses)
}

function Write-AccessInfo {
    if ([string]::IsNullOrWhiteSpace($ImagesRoot)) {
        $ImagesRoot = Find-ComfyOutput
    }
    if ([string]::IsNullOrWhiteSpace($ImagesRoot)) {
        $ImagesRoot = Join-Path $ProjectRoot "lora_datasets"
    }
    $resolvedImagesRoot = (Resolve-Path -LiteralPath $ImagesRoot -ErrorAction SilentlyContinue).Path
    if ([string]::IsNullOrWhiteSpace($resolvedImagesRoot)) {
        $resolvedImagesRoot = $ImagesRoot
    }
    try {
        Set-Content -LiteralPath $ImagesRootFile -Value $resolvedImagesRoot -Encoding UTF8
    } catch {
        Write-Warning ("Could not update optional gallery image-root metadata: {0}" -f $_.Exception.Message)
    }
    $lines = @(
        "Local URL: $GalleryUrl",
        "Listen address: 0.0.0.0:$Port",
        ""
    )
    $tailscaleAddresses = @(Find-TailscaleIPv4)
    if ($tailscaleAddresses.Count -gt 0) {
        $lines += "Tailscale URL(s):"
        foreach ($address in $tailscaleAddresses) {
            $lines += "http://$address`:$Port/"
        }
    } else {
        $lines += "Tailscale IPv4: not detected"
        $lines += "Local access remains available."
    }
    $lines += ""
    $lines += "This file is generated by start_gallery.bat."
    try {
        $lines | Set-Content -LiteralPath $AccessInfoFile -Encoding UTF8
    } catch {
        Write-Warning ("Could not update optional gallery access metadata: {0}" -f $_.Exception.Message)
    }
}

$mutex = [System.Threading.Mutex]::new($false, $MutexName)
$mutexAcquired = $false
$serverProcess = $null
try {
    try {
        $mutexAcquired = $mutex.WaitOne(0)
    } catch [System.Threading.AbandonedMutexException] {
        $mutexAcquired = $true
    }

    if (-not $mutexAcquired) {
        # Another launcher is already starting the server. Do not create a duplicate.
        if (Wait-GalleryReady) { Write-AccessInfo; Start-Process $GalleryUrl }
        exit 0
    }

    if (Test-GalleryReady) {
        Write-AccessInfo
        Start-Process $GalleryUrl
        exit 0
    }

    if ([string]::IsNullOrWhiteSpace($ImagesRoot)) {
        $ImagesRoot = Find-ComfyOutput
    }
    if ([string]::IsNullOrWhiteSpace($ImagesRoot)) {
        $ImagesRoot = Join-Path $ProjectRoot "lora_datasets"
    }

    $venvPython = Join-Path $ProjectRoot ".venv\Scripts\python.exe"
    if (Test-Path -LiteralPath $venvPython) {
        $python = (Resolve-Path -LiteralPath $venvPython).Path
    } else {
        $pythonCommand = Get-Command python.exe -ErrorAction Stop
        $python = $pythonCommand.Source
    }

    Import-GallerySecretEnvironment

    New-Item -ItemType Directory -Force -Path $PidDirectory | Out-Null
    $argumentList = @(
        "gallery_server.py",
        "--images-root", ('"{0}"' -f $ImagesRoot),
        "--host", "0.0.0.0",
        "--port", $Port.ToString()
    )
    $serverProcess = Start-Process -FilePath $python -ArgumentList $argumentList -WorkingDirectory $ProjectRoot -WindowStyle Hidden -PassThru
    $pidRecord = [ordered]@{
        pid = $serverProcess.Id
        process_path = $python
        started_at_utc_ticks = $serverProcess.StartTime.ToUniversalTime().Ticks
    }
    $pidRecord | ConvertTo-Json | Set-Content -LiteralPath $PidFile -Encoding UTF8

    if (Wait-GalleryReady) {
        Write-AccessInfo
        Start-Process $GalleryUrl
        exit 0
    }

    if ($serverProcess -and -not $serverProcess.HasExited) {
        Stop-Process -Id $serverProcess.Id -Force -ErrorAction SilentlyContinue
    }
    Remove-Item -LiteralPath $PidFile -Force -ErrorAction SilentlyContinue
    throw "Gallery server startup timed out."
} catch {
    New-Item -ItemType Directory -Force -Path $PidDirectory | Out-Null
    $_ | Out-String | Set-Content -LiteralPath (Join-Path $PidDirectory "last_launch_error.txt") -Encoding UTF8
    exit 1
} finally {
    if ($mutexAcquired) { $mutex.ReleaseMutex() }
    $mutex.Dispose()
}
